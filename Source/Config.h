{
    //##########################################################################
    //##                                                                      ##
    //##   ★★★  ГЛАВНЫЕ РУЧКИ FUTURE — КРУТИТЬ В ПЕРВУЮ ОЧЕРЕДЬ  ★★★          ##
    //##                                                                      ##
    //##   Три числа, которыми настраивается баланс «сжатие против громкости». ##
    //##   Вынесены наверх намеренно: остальной файл — тонкая настройка,       ##
    //##   а эти правятся на слух чаще всего.                                 ##
    //##                                                                      ##
    //##########################################################################

    //  ┌────────────────────────────────────────────────────────────────────┐
    //  │  1. ГЛУБИНА СЖАТИЯ — на сколько dB ниже самого громкого тона       │
    //  │     стоит порог.                                                   │
    //  │                                                                    │
    //  │     МЕНЬШЕ число = порог ВЫШЕ = жмётся только верхушка             │
    //  │     БОЛЬШЕ число = порог ныряет глубже = жмётся тело микса         │
    //  └────────────────────────────────────────────────────────────────────┘
    //
    //  История значения — чтобы её не переоткрывать заново:
    //    14 — порог висел так высоко, что через него почти ничего не проходило:
    //         COMP −0.1 против −1.6 у MODERN, а всё несжатое доедал лимитер
    //         (LIM −21 против −14). Поштучная обработка тонов на глубине
    //         −0.1 dB себя не проявляет — там любой алгоритм звучит одинаково.
    //    26 — подводило тело микса под сжатие, движок начинал реально работать,
    //         но на слух выходило пережато.
    //    12 — жмётся только верхушка, тело не трогаем.
    //    14 — текущее, пробуем на слух.
    //
    //  ⚠ ВАЖНО про историю выше: цифры «COMP −0.1» и «COMP −2.6», которыми
    //  обосновывали подъём до 26, оказались АРТЕФАКТОМ МЕТРА. Он усреднял гейн по
    //  всем ~1000 ячейкам спектра, включая нежатые, и занижал реальную редукцию
    //  примерно на 5 dB (проверено моделью). При этом рядом стоял LIM, который
    //  показывает честный МАКСИМУМ за блок — то есть среднее сравнивали с пиком.
    //  Метр исправлен, но выводы, сделанные по нему до исправления, недостоверны.
    //  Не поднимай это число, опираясь на разрыв COMP/LIM: они и сейчас считаются
    //  по-разному, LIM по своей природе всегда крупнее.
    constexpr float futureThreshDb = 14.0f;

    //  ┌────────────────────────────────────────────────────────────────────┐
    //  │  2. ГРОМКОСТЬ ОТ AMOUNT — крутишь AMOUNT, прибавляется громкость.  │
    //  │                                                                    │
    //  │     makeupLink = ДОЛЯ подъёма:  1.00 полный, 0.75 мягче (сейчас)   │
    //  │     staticMakeupMaxDb = его ПОТОЛОК в dB при AMOUNT 100%           │
    //  │                                                                    │
    //  │     Уменьшай, если слышно ПЕРЕЖАТИЕ. Увеличивай, если тихо/слабо.  │
    //  └────────────────────────────────────────────────────────────────────┘
    //
    //  Итог в dB = AMOUNT × staticMakeupMaxDb × makeupLink.
    //  Сейчас при AMOUNT 20% это 20% × 6 × 0.75 = 0.9 dB.
    //  Работает во ВСЕХ режимах, не только в FUTURE.
    constexpr float makeupLink        = 0.75f;
    constexpr float staticMakeupMaxDb = 6.0f;

    //  ┌────────────────────────────────────────────────────────────────────┐
    //  │  3. ГРОМКОСТЬ, ПРИВЯЗАННАЯ К РЕДУКЦИИ (только FUTURE) — какую долю │
    //  │     реально снятого мейкап возвращает обратно.                     │
    //  │                                                                    │
    //  │     Это НЕ пункт 2: тот считается от положения ручки, а этот —     │
    //  │     от того, сколько движок фактически придавил.                   │
    //  │     1.0 вернуло бы ВСЁ — AMOUNT перестал бы менять громкость       │
    //  │     0   = мейкап не видит редукцию вообще (как было раньше)        │
    //  └────────────────────────────────────────────────────────────────────┘
    //
    //  Зачем: пункт 2 растёт вчетверо медленнее сжатия. На переходе с AMOUNT
    //  20% на 50% сжатие забирало +4.5 dB, а мейкап возвращал +1.35 — отсюда
    //  «на 20% лучше классика, на 50% пережат и тихий». Это дефект НАКЛОНА,
    //  константой он только сдвигается, поэтому появился этот второй путь.
    //  Замерено: потеря на этом переходе была −3.15 dB, стала +0.62 dB.
    constexpr float futureMakeupLink = 0.75f;

    //  ┌────────────────────────────────────────────────────────────────────┐
    //  │  4. ОБЩИЙ МНОЖИТЕЛЬ СЖАТИЯ. 1.0 = полная сила.                     │
    //  │     ⚠ Трогать в ПОСЛЕДНЮЮ очередь — обычно нужен пункт 1, не этот. │
    //  └────────────────────────────────────────────────────────────────────┘
    //
    //  Это множитель УЖЕ ПОСЧИТАННОЙ редукции, то есть НЕ «жать мягче», а
    //  «жать точно так же и подкрутить фейдер»: ratio остаётся жёстким,
    //  характер сжатия тот же, просто тише. Пробовали 0.65 и 0.4745 — сжатие
    //  звучало ровно так же пережато, зато компрессор переставал снимать пики
    //  и они уезжали в лимитер (COMP −2.6 против LIM −23.6).
    //  Глубину сжатия правит пункт 1, а не это.
    constexpr float futureCompScale = 1.0f;

    //##########################################################################
    //##   Ниже — тонкая настройка. Обычно трогать не требуется.              ##
    //##########################################################################

    //--------------------------------------------------------------------------
    // ГРАНИЦЫ ПОЛОС режима ALL MIX COMP (Гц). Делят звук на 4 полосы:
    //   LOW    : 0 .. bandSplit1
    //   LO-MID : bandSplit1 .. bandSplit2
    //   HI-MID : bandSplit2 .. bandSplit3
    //   HIGH   : bandSplit3 .. 20000
    //--------------------------------------------------------------------------
    constexpr float bandSplit1Hz = 160.0f;   // НИЗ / низ-середина
    constexpr float bandSplit2Hz = 1500.0f;  // низ-середина / верх-середина
    constexpr float bandSplit3Hz = 7000.0f;  // верх-середина / ВЕРХ

    //--------------------------------------------------------------------------
    // КОМПРЕССОР (Stage 1).
    //--------------------------------------------------------------------------
    // RMS-окно детектора. Больше = плавнее/ровнее (меньше дёргается на ударах),
    // меньше = быстрее реагирует.
    constexpr float compRmsMs = 50.0f;

    // МЯГКОЕ КОЛЕНО (dB) — ширина плавного входа в сжатие вокруг порога.
    // Больше = мягче/незаметнее вход, меньше = резче. 0 = жёсткое колено.
    constexpr float compKneeDb = 6.0f;

    //--------------------------------------------------------------------------
    // РЕЖИМ MODERN (кнопка CLASSIC|MODERN). Эти настройки работают ТОЛЬКО в
    // MODERN; в CLASSIC звук остаётся прежним.
    //--------------------------------------------------------------------------
    // Сайдчейн-фильтр ДЕТЕКТОРА (Гц). Компрессор перестаёт "видеть" низ, поэтому
    // кик/бас не тянут вниз весь трек. На сам звук фильтр НЕ влияет — только на
    // то, что слышит детектор. Больше = меньше реакции на низ.
    constexpr float scHpfHz = 70.0f;

    // Сглаживание огибающей гейна (мс). Скругляет резкие изломы (углы) огибающей,
    // из-за которых на басу появлялась грязь. Скорости атаки/релиза НЕ меняет.
    constexpr float gainSmoothMs = 0.6f;

    // RATIO — жёсткость сжатия. Больше = жёстче выравнивает.
    constexpr float ratioPunch = 4.0f;

    // ПАМЯТЬ УРОВНЯ — средний уровень, от которого считается ПОРОГ. ОЧЕНЬ медленная
    // (несколько секунд), чтобы порог стоял на месте и НЕ плавал за киком.
    // Больше = стабильнее (3000-6000). Меньше = подвижнее.
    constexpr float levelMemoryMs = 2000.0f;

    // ТРАНЗИЕНТ-АДАПТИВНАЯ ПАМЯТЬ (умная): когда уровень РЕЗКО меняется (смена
    // секции, дроп, переключение AUTO/LUFS), память временно ускоряется до
    // memoryRiseMs, чтобы порог мгновенно догнал новый уровень (без 3-5 сек лага).
    // memoryBigJumpDb — насколько громче/тише памяти должен быть сигнал, чтобы
    // считать это «резким скачком» и ускорить память. Меньше = чувствительнее.
    constexpr float memoryRiseMs    = 40.0f;   // быстрая память на резком скачке
    constexpr float memoryBigJumpDb = 6.0f;    // порог «резкого скачка» (dB)

    // ПОРОГ относительно памяти: threshold = память - thresholdOffsetDb.
    // Больше = порог ниже = жмёт сильнее/чаще. Меньше = мягче.
    // (Ручка CHARACTER масштабирует это: влево мягче, вправо глубже.)
    constexpr float thresholdOffsetDb = 6.0f;

    // МАКС. на сколько dB компрессор может ПРИДАВИТЬ при AMOUNT=100%. 12 dB =
    // уверенное сжатие без провала в пол, даже если порог чуть отстал.
    constexpr float downRangeDb = 12.0f;

    //==========================================================================
    //  СИЛА СЖАТИЯ ПО ПОЛОСАМ (режим ALL MIX COMP) — множитель поверх ручки полосы.
    //    1.0 = полоса жмётся ровно как показывает её ручка.
    //    0.7 = эта полоса жмётся на 70% (мягче) — верха не пропадают.
    //    1.3 = жёстче.  0.0 = не жмётся вообще.
    //  Порядок: [0] LOW  [1] LO-MID  [2] HI-MID  [3] HIGH
    //==========================================================================
    constexpr float bandStrengthScale[4] = { 1.0f, 1.0f, 0.8f, 0.7f };
    //                                        LOW   LOMID HIMID HIGH

    //--------------------------------------------------------------------------
    // ГРОМКОСТЬ / MAKE-UP (перед клиппером).
    //--------------------------------------------------------------------------
    // makeupLink и staticMakeupMaxDb ПЕРЕЕХАЛИ В ШАПКУ ФАЙЛА (пункт 2) — правь там.

    // CLIP DRIVE от AMOUNT — на сколько dB ручка AMOUNT загоняет сигнал В клиппер
    // на максимуме. Это главная «ровность»: уровень вверх -> срез по потолку.
    // Больше = ровнее/жёстче (но больше искажений). Меньше = мягче.
    constexpr float clipDriveMaxDb = 12.0f;

    //--------------------------------------------------------------------------
    // ПИКОВЫЙ ЛИМИТЕР (Stage 2, после компрессора, перед клиппером).
    //--------------------------------------------------------------------------
    // Двухступенчатый релиз: быстрый + медленный (берётся max), чтобы гейн не
    // «рябил» вслед за волной баса => чище низ при сильном лимитировании.
    constexpr float limiterRelFastMs = 30.0f;  // быстрая ступень
    constexpr float limiterRelSlowMs = 150.0f; // медленная ступень
    constexpr float limiterHoldMs    = 3.0f;   // удержание перед релизом

    // LOOKAHEAD — на сколько мс лимитер «заглядывает вперёд» (и на столько же задержка).
    constexpr float lookaheadMs = 2.0f;

    // СПЕКТРАЛЬНЫЙ ЛИМИТЕР — потолок полос относительно мастер-потолка.
    // <1 = полосы лимитятся чуть ниже => спектральное действие реально работает.
    constexpr float specBandCeilingScale = 0.84f;

    //==========================================================================
    //  РЕЖИМ PHASE — громкость без сжатия (третья позиция SMART | IRC IV | PHASE)
    //
    //  Сейчас громкость делает ЛИМИТЕР: INPUT и AMOUNT загоняют в него сигнал
    //  сильнее, он давит сильнее. Лимитер — самый грубый инструмент в цепи, и чем
    //  больше на него валится, тем меньше остаётся живого.
    //
    //  Наблюдение, которое всё меняет: пик волны определяется НЕ энергией, а тем,
    //  как совпали ФАЗЫ тонов. Много тонов сошлось в одной точке — большой выброс.
    //  Развёл фазы — пик упал, а ГРОМКОСТЬ НЕ ИЗМЕНИЛАСЬ: громкость это энергия,
    //  а энергия от фазы не зависит. Ухо к фазе почти глухо.
    //
    //  Значит каждый снятый так децибел — это децибел громкости ДАРОМ: без
    //  сжатия, без лимитирования, без искажений. И снимается он ДО лимитера,
    //  поэтому лимитеру достаётся заметно меньше работы.
    //
    //  Делается каскадом всепропускающих фильтров: они меняют фазу, но НЕ АЧХ —
    //  тембр не трогается вообще, по построению.
    //==========================================================================

    // Сколько секций в каскаде. Больше = глаже разброс фазы и сильнее эффект,
    // но и больше размазывание транзиента.
    constexpr int dispSections = 6;

    // Диапазон, в котором работает каскад (Гц). Крест-фактор хауса живёт внизу —
    // там кик, там и пики. Выше 300 Гц разводить фазы уже вредно: размажет атаку.
    constexpr float dispLoHz = 25.0f;
    constexpr float dispHiHz = 250.0f;

    // Добротность секций. Меньше = шире и мягче поворот фазы, больше = резче и
    // сильнее разброс задержки. Главная ручка настройки характера.
    constexpr float dispQ = 0.55f;

    //--- АДАПТИВНОЕ РАЗМЕЩЕНИЕ КАСКАДА ---------------------------------------
    //  Идея взята от IRC: смотреть по полосам. Но НЕ его механизм — IRC режет
    //  сигнал кроссоверами, а нам резать нельзя: всепропускающий каскад чист
    //  именно тем, что он ОДИН непрерывный. Поэтому полосы здесь только
    //  ИЗМЕРЯЮТ (звук через детекторы не идёт), а каскад целиком переезжает
    //  туда, где крест-фактор реально выше.
    //
    //  Зачем: жёстко прошитые 25-250 Гц дают запас только низу — отсюда перекос,
    //  когда бас проходит свободнее остального. Если пик делает не кик, а снейр
    //  или бас-лид в низкой середине, фиксированный диапазон его просто пропустит.
    constexpr bool dispAdaptive = true;

    // Жёсткие границы, за которые каскад не выезжает НИКОГДА (Гц).
    // Верхняя — принципиальна: у кика транзиент это начало звука, у хэта транзиент
    // это ВЕСЬ звук. Разводить фазы наверху = размазать верх. Равномерности по
    // всему спектру не будет и не должно быть.
    constexpr float dispMinHz = 25.0f;
    constexpr float dispMaxHz = 1200.0f;

    // Во сколько раз каскад шире своего центра в каждую сторону.
    constexpr float dispSpread = 3.2f;

    // Выше этой частоты крест-фактор НЕ учитывается при выборе центра — иначе
    // хэты перетянули бы каскад наверх, где он вредит.
    constexpr float dispHfCapHz = 2000.0f;

    // Макс. скорость переезда центра (доля/сек). Медленно, чтобы переезд не
    // читался как фазер.
    constexpr float dispGlideRate = 0.15f;

    // Окно измерения крест-фактора по полосам (сек).
    constexpr float dispSearchSec = 0.5f;

    //--------------------------------------------------------------------------
    // КЛИППЕР (Stage 3).
    //--------------------------------------------------------------------------
    // asym — лёгкая асимметрия верх/низ (0 = симметрично, 0.2 = с панчем).
    // ADAA — антиалиасинг по производной (чисто на пиках, «дорогой» звук клиппера).
    constexpr float clipAsym = 0.10f;
    constexpr bool  clipADAA = true;

    // ЗАПАС ПОД ВЫБРОС ДАУНСЭМПЛЕРА. Клиппер режет в оверсэмплированном домене чуть
    // НИЖЕ потолка, потому что мин-фазный полуполосный фильтр на обратном пути
    // добавляет маленький выброс. Без запаса этот выброс приходилось срезать
    // жёстким clamp'ом на базовой частоте — а это клип БЕЗ антиалиасинга, ровно та
    // грязь, ради которой и стоит 16x. 0.98 ≈ -0.17 dB. Меньше = больше запаса
    // (чище, чуть тише), 1.0 = без запаса (как было).
    constexpr float clipDownGuard = 0.98f;

    // Длина гладкого «провала» гейна, которым ловится остаточный выброс после
    // даунсэмплинга (в отсчётах). Вместо обрезания — короткое плавное приседание,
    // оно не создаёт гармоник. Больше = плавнее/незаметнее, меньше = точнее.
    constexpr int clipDipSamples = 16;

    //--------------------------------------------------------------------------
    // ВЫХОДНОЙ ПОТОЛОК (значение по умолчанию для ручки Ceiling). -0.1 dBFS.
    //--------------------------------------------------------------------------
    constexpr float defaultCeilingDb = -0.1f;

    //==========================================================================
    //  РЕЖИМ MASK (третья позиция переключателя CLIP | HI-Q | MASK)
    //
    //  Обычный клиппер срезает верхушку волны. Срез — это резкое событие, у него
    //  энергия по ВСЕМУ спектру, поэтому каждый удар кика подрубает хэты и верх.
    //  MASK вместо среза ВЫЧИТАЕТ из сигнала короткий импульс, поставленный точно
    //  в момент пика. Спектр импульса подобран заранее — под то, что сейчас громко
    //  и потому маскирует искажения. Пик снимается ровно так же, но грязь ложится
    //  туда, где её не слышно.
    //==========================================================================

    // Глубина режима. 1.0 = полностью. 0.0 = MASK работает как HI-Q (нужно для
    // проверки: при 0 рендер обязан совпасть с HI-Q побитово).
    constexpr float maskAmount = 1.0f;

    // Длина импульса отмены в отсчётах. Задержка режима = ровно это число.
    // Больше = точнее по частоте (лучше разделяет низ и верх), но больше задержка.
    constexpr int maskKernelLen = 128;

    // Границы трёх полос ИМПУЛЬСА (Гц). Импульс короткий, поэтому полос всего три —
    // разделить 90 и 200 Гц таким импульсом физически нельзя, а «не вываливать
    // ошибку кика в хэты» тремя полосами решается полностью.
    constexpr float maskKernelLoHz = 400.0f;   // НИЗ / СЕРЕДИНА
    constexpr float maskKernelHiHz = 4000.0f;  // СЕРЕДИНА / ВЕРХ

    // Сколько проходов отмены пиков. Близкие пики влияют друг на друга, поэтому
    // одного прохода мало. Остаток добирает обычный клиппер.
    constexpr int maskIters        = 2;   // в реальном времени
    constexpr int maskItersOffline = 4;   // при рендере (там торопиться некуда)

    // РАЗМЫТИЕ МАСКИРОВКИ — то, что делает режим психоакустическим, а не просто
    // многополосным. Громкий звук маскирует соседние частоты: ВВЕРХ по частоте
    // сильно, вниз слабо. Больше = маскировка расползается дальше = грязь можно
    // класть в больше полос.
    constexpr float maskSpreadUpDb   = 10.0f;  // ползёт вверх по частоте
    constexpr float maskSpreadDownDb = 25.0f;  // и вниз (слабее)

    // На сколько dB ниже громкого звука искажение перестаёт быть слышным.
    // Больше = осторожнее (грязи кладём меньше), меньше = агрессивнее.
    constexpr float maskDepthDb = 14.0f;

    // Детектор громкости полос: как быстро следит за уровнем.
    constexpr float maskLevelAtkMs = 1.0f;    // атака
    constexpr float maskLevelRelMs = 50.0f;   // релиз

    // Сглаживание формы импульса (мс) — чтобы он не дёргался от блока к блоку.
    constexpr float maskWeightSmMs = 5.0f;

    // МИНИМАЛЬНЫЙ вес полосы. Не даёт импульсу выродиться в чистый низ: если
    // полностью запретить верх, импульс станет очень широким и сам начнёт
    // создавать новые пики. 0.12 = полосе всегда достаётся хотя бы 12%.
    // Меньше = агрессивнее прячем грязь (но риск «раздувания» импульса).
    constexpr float maskWeightFloor = 0.12f;

    //--------------------------------------------------------------------------
    //  NOISE-SHAPING ДОБИВКА (внутри MASK). ПО УМОЛЧАНИЮ ВЫКЛЮЧЕНА.
    //
    //  То, что импульсы отмены не добрали, дожимается петлёй обратной связи,
    //  которая сдвигает остаточную ошибку вниз по частоте — под кик.
    //
    //  ЧЕСТНО О МИНУСАХ (поэтому и выключено):
    //   1. Петля работает на базовой частоте, без антиалиасинга. Остаток после
    //      отмены пиков маленький, поэтому и грязи мало — но она есть.
    //   2. Любой noise-shaping УВЕЛИЧИВАЕТ суммарную энергию ошибки, просто
    //      перекладывает её туда, где не слышно. Это не бесплатно.
    //   3. В дизеринге ошибка почти белая и петля устойчива. Здесь ошибка сильно
    //      связана с сигналом, и петля вокруг жёсткой нелинейности может зазвенеть.
    //      Поэтому фидбэк жёстко ограничен (maskNsClamp).
    //  Включать ПОСЛЕДНЕЙ и слушать бас отдельно. Звенит — выключай обратно.
    //--------------------------------------------------------------------------
    constexpr bool maskNoiseShape = false;

    // Коэффициенты петли (2-й порядок, выше не надо — опаснее). При a1 = -0.9
    // ошибка на низах усиливается ~1.9x, на верхах давится до ~0.1x, то есть
    // грязь уезжает под кик. Ближе к 0 = слабее эффект и безопаснее.
    constexpr float maskNsA1 = -0.90f;
    constexpr float maskNsA2 =  0.0f;

    // Жёсткий предел фидбэка (доля от потолка) — страховка от звона.
    constexpr float maskNsClamp = 0.25f;

    //--------------------------------------------------------------------------
    //  ФАЗОВЫЙ РОТАТОР (работает внутри режима MASK)
    //
    //  У хаус-кика пик высокий не потому, что в нём много энергии, а потому что
    //  форма волны кривая (несимметричная). Всепропускающий фильтр меняет ФАЗУ,
    //  но не АЧХ — то есть меняет высоту пика, НЕ меняя того, что слышно.
    //  Плагин сам медленно ищет фазу, при которой пик ниже: это 1-3 dB запаса
    //  громкости вообще без искажений, до того как клиппер что-то сделал.
    //--------------------------------------------------------------------------
    constexpr bool maskPhaseRotate = true;   // выключить ротатор целиком

    // Границы поиска частоты (Гц). Ниже 30 фильтр уже ничего полезного киком не
    // делает, выше 200 начинает крутить бас, а не асимметрию кика.
    constexpr float rotMinHz = 30.0f;
    constexpr float rotMaxHz = 200.0f;

    // Добротность фильтра. Меньше = шире и мягче поворот фазы.
    constexpr float rotQ = 0.6f;

    // Окно измерения крест-фактора (сек). Больше = решение устойчивее, но поиск
    // медленнее реагирует на смену материала.
    constexpr float rotSearchSec = 1.0f;

    // Насколько разнесены пробники по частоте (во сколько раз). Пробники ТОЛЬКО
    // измеряют — звук через них не идёт.
    constexpr float rotProbeSpread = 1.3f;

    // МАКС. скорость ухода частоты (доля в секунду). 0.02 = 2%/сек — медленнее
    // любого слышимого фазера, поэтому уход не читается как свип.
    constexpr float rotGlideRate = 0.02f;

    //==========================================================================
    //  ДВИЖОК FUTURE (третья позиция переключателя CLASSIC | MODERN | FUTURE)
    //
    //  Идея: обычный компрессор умножает ВЕСЬ сигнал на одно число. Отсюда все
    //  три классические беды сразу — детектор не различает кик и вокал, атака
    //  спорит с панчем, а само умножение модулирует бас и делает грязь.
    //  FUTURE разбирает звук на отдельные тона, чтобы потом менять громкость
    //  КАЖДОГО отдельно. Общего гейна нет — значит и качать нечему.
    //
    //  СЕЙЧАС ЗДЕСЬ ТОЛЬКО РАЗБОР И ОБРАТНАЯ СБОРКА, БЕЗ СЖАТИЯ.
    //  Это проверка фундамента: если звук не собирается обратно прозрачно, всё
    //  остальное строить не на чем. Включил FUTURE — должно звучать как MODERN.
    //==========================================================================

    // Размер окна анализа (степень двойки: 11 = 2048 отсчётов).
    // Больше = лучше разбирает бас по частоте, но больше задержка.
    //   10 = 1024 (задержка ~16 мс)   11 = 2048 (~32 мс)   12 = 4096 (~64 мс)
    constexpr int futureFftOrder = 11;

    // Насколько густо окна перекрываются: 4 = шаг в четверть окна (75% нахлёста).
    // Меньше 4 брать нельзя — сборка перестанет быть точной.
    constexpr int futureOverlap = 4;

    //--- Сжатие по тонам ------------------------------------------------------
    // futureThreshDb ПЕРЕЕХАЛ В ШАПКУ ФАЙЛА (пункт 1) — правь там.

    // Жёсткость сжатия каждого тона. Больше = жёстче.
    constexpr float futureRatio = 4.0f;

    // Макс. на сколько dB можно придавить ОДИН тон.
    constexpr float futureMaxRedDb = 12.0f;

    // Скорости огибающей КАЖДОГО тона (мс). У каждого тона она своя — поэтому кик
    // не тянет за собой хэты, и «накачки» нет в принципе.
    constexpr float futureAtkMs = 5.0f;
    constexpr float futureRelMs = 80.0f;

    // Память уровня (мс): от неё считается порог. Больше = стабильнее.
    constexpr float futureMemMs = 400.0f;

    // futureCompScale и futureMakeupLink ПЕРЕЕХАЛИ В ШАПКУ (пункты 3 и 4) — правь там.

    // Спад пикового следящего ПО КАЖДОМУ тону (мс). От него зависит совсем другое:
    // когда SMART считает тон «стихшим» и какую ноту выбирает AUTO.
    // Раньше обе задачи брали futureMemMs. Работало (400 мс случайно подошли обеим),
    // но связь была невидимой: подкрутишь память уровня ради порога — молча уедут
    // SMART-релиз и выбор AUTO. Теперь это отдельное число. Значение прежнее, поэтому
    // звук не изменился. Меньше = тон быстрее считается стихшим.
    constexpr float futurePeakMemMs = 400.0f;

    //--- ВОЗРАСТ ТОНА (защита атаки) -----------------------------------------
    // Только что появившийся тон НЕ жмётся — его атака проходит нетронутой, и
    // сжатие вводится плавно за futureAgeFrames кадров. Именно это снимает вечный
    // спор «быстрая атака против панча»: панч сохраняется у каждого тона отдельно.
    // Больше = дольше защищаем атаку (панчевее, но меньше контроля).
    constexpr int futureAgeFrames = 3;

    // Во сколько раз должна подскочить громкость тона, чтобы это считалось новой
    // атакой. Меньше = чувствительнее (защищаем чаще).
    constexpr float futureOnsetRise = 1.4f;

    // Сглаживание гейна ПО ЧАСТОТЕ. Ширина берётся не в ячейках, а в долях
    // КРИТИЧЕСКОЙ ПОЛОСЫ СЛУХА: 3 = ровно одна критическая полоса, меньше = уже,
    // больше = шире. 0 = выключить.
    //
    // Почему не в ячейках: постоянная ширина в герцах неверна в обе стороны.
    // Семь ячеек — это полторы октавы на 50 Гц (кик, саб и бас-нота сливались в
    // один гейн, то есть независимость тонов внизу уничтожалась) и сотая доля
    // октавы на 8 кГц, где сглаживание не делало вообще ничего.
    constexpr int futureBinSmooth = 3;

    //--- 1. МАСКИРОВКА МЕЖДУ ТОНАМИ ------------------------------------------
    // Громкий кик физически ПРЯЧЕТ соседние тоны — их не слышно, значит и жать их
    // незачем. Каждый тон отбрасывает «тень» вверх по частоте (сильно) и вниз
    // (слабо); тон, накрытый чужой тенью, почти не сжимается.
    // Наклоны заданы на БАРК (единица слуха), а не на ячейку — иначе на верхах
    // тень расползалась бы в разы быстрее, чем слышит ухо.
    constexpr float futureMaskSpreadUpDb   = 10.0f;  // тень вверх по частоте
    constexpr float futureMaskSpreadDownDb = 25.0f;  // и вниз (слабее)

    // На сколько dB тон должен уйти под чужую тень, чтобы считаться полностью
    // скрытым. Меньше = агрессивнее пропускаем замаскированное (громче, но риск
    // недожать то, что всё-таки слышно).
    constexpr float futureMaskDepthDb = 12.0f;

    //--- 3. УМНЫЙ ВОЗРАСТ ----------------------------------------------------
    // Защита атаки теперь зависит от того, НАСКОЛЬКО резко вскочил тон: у кика
    // атака короткая, у пэда длинная. Чем резче скачок, тем дольше не жмём.
    // Верхний предел, чтобы длинный нарастающий звук не остался без контроля.
    constexpr int futureAgeMaxFrames = 12;

    //--- ЗАЩИТА АТАКИ В ПЕРИОДАХ ВОЛНЫ (только FUTURE 2) ---------------------
    // Кадр — это одно и то же время для всех частот, а значит РАЗНОЕ число периодов.
    // 3 кадра = 32 мс: на 8 кГц это 250 периодов (вечность), на 50 Гц — полтора.
    // То есть фиксированное число кадров сильнее всего обделяет низ, где панч и
    // живёт. Ровно тот же довод, из-за которого ATTACK в FUTURE считается в периодах.
    //
    // Обе величины берутся как МАКСИМУМ с кадровыми, поэтому выше ~100 Гц не
    // меняется ничего — двигается только саб и фундамент кика.
    // Больше = кик держит панч дольше, но его тело меньше под контролем.
    constexpr float futureAgeCycles    = 3.0f;    // база защиты, в периодах тона
    constexpr float futureAgeMaxCycles = 12.0f;   // верхний предел, в периодах тона

    //--- 2. ГАРМОНИЧЕСКАЯ СВЯЗКА ---------------------------------------------
    // 50 Гц и 150 Гц — это ОДИН кик, а не два независимых тона. Если жать их
    // по-разному, у кика меняется тембр. Связка подтягивает гейн обертонов к
    // гейну основного тона: кик становится ровнее, но остаётся собой.
    // 0 = выключить связку, 1 = обертоны жмутся ровно как основной тон.
    constexpr float futureHarmonicLink = 0.5f;

    // Основной тон ищется НИЖЕ этой частоты (кик/бас — то, ради чего всё делается).
    constexpr float futureHarmonicMaxHz = 300.0f;

    // Сколько обертонов подтягивать.
    constexpr int futureHarmonicCount = 8;

    //--- 4. ПОДЪЁМ ТИХИХ ТОНОВ ----------------------------------------------
    // Мы не только давим громкое, но и ПОДНИМАЕМ тихое: хвосты ревера, воздух,
    // детали, которые обычно тонут. На отдельных тонах это безопасно — общего
    // гейна нет, поэтому шум между ударами не лезет вверх (за это и не любят
    // обычную upward-компрессию).
    // 0 = выключить подъём.
    // Был 3.0 — и это делало ручку почти двухпозиционной: расчёт давал 11 дБ, потолок
    // резал до 3, а маскировка добивала до ~0.9 дБ. То есть что бы ручка ни считала,
    // результат был один и ниже порога слышимости. 7 дБ возвращает формуле смысл:
    // ручка снова управляет глубиной подъёма, а не просто включает его.
    //
    // Подъём выходит на этот потолок примерно через 9 дБ и дальше ДЕРЖИТ его. Полка —
    // не дефект, а насыщение: чем тише тон, тем больше подъём, до предела. Пробовали
    // растянуть рампу на всё окно — форма стала треугольной, и у самых тихих тонов
    // подъём снова падал (то есть наоборот тому, ради чего апворд и сделан), а на
    // типичных уровнях ослаб вдвое. Откатили по слуху.
    constexpr float futureUpMaxDb = 7.0f;

    // Насколько ниже памяти уровня начинается подъём. Больше = поднимаем более
    // тихие вещи.
    constexpr float futureUpThreshDb = 30.0f;

    // Ниже этого (относительно памяти уровня) НЕ поднимаем вообще — иначе полезет
    // шум и «воздух» из тишины. Это страховка, трогать в последнюю очередь.
    constexpr float futureUpFloorDb = 60.0f;

    // Насколько плавно подъём УХОДИТ у самого пола. Без этого стоял обрыв: тон на
    // 59.9 дБ ниже памяти получал все +7 дБ, а на 60.1 — ноль. Ступенька в 7 дБ ровно
    // там, ради чего апворд и сделан: затухающий хвост ревера переходит границу и его
    // дёргает вниз. Это «дыхание гейта», только наоборот. Теперь на последних дБ перед
    // полом подъём сводится к нулю, и хвост уходит ровно.
    // Больше = мягче уход, но подъём начинает слабеть раньше.
    constexpr float futureUpFadeDb = 10.0f;

    //--- ALL MIX В РЕЖИМЕ FUTURE ---------------------------------------------
    //  Обычный ALL MIX режет сигнал кроссоверами на 4 полосы, жмёт каждую и
    //  складывает обратно — отсюда фазовые провалы на стыках и необходимость
    //  выравнивать полосы всепропускающими фильтрами.
    //
    //  В FUTURE резать НЕЧЕГО: спектр уже разобран на тона. Четыре ручки просто
    //  задают, насколько сильно жать тона своего диапазона. Кроссоверов нет —
    //  значит нет и стыков. И внутри полосы тона остаются независимыми: кик и
    //  бас в полосе LOW сохраняют свои отдельные огибающие, а не жмутся одним
    //  общим гейном, как в классическом мультибэнде.
    //
    //  Ширина плавного перехода между соседними полосами (в октавах). Переход
    //  делается по частоте, а не резким срезом. 0 = жёсткая граница.
    constexpr float futureBandBlendOct = 0.5f;

    //--- 5. ТОНЫ ПРОТИВ ШУМА -------------------------------------------------
    // Хэты и воздух — это ШУМ, а не тоны, и жать их по тональной логике неверно.
    // Тональность определяется по предсказуемости фазы: у настоящего тона фаза от
    // кадра к кадру поворачивается ровно, у шума — как попало.
    // Во сколько раз слабее жать шум. 1.0 = не различать, 0 = не жать шум совсем.
    constexpr float futureNoiseScale = 0.6f;

    // Сглаживание оценки тональности (мс) — чтобы она не мигала.
    constexpr float futureTonalSmMs = 30.0f;

    //--------------------------------------------------------------------------
    //  ПЕРЕИЗОБРЕТЁННЫЕ АТАКА И РЕЛИЗ (только в FUTURE)
    //
    //  Обычные ручки задают ВРЕМЯ в миллисекундах. Но музыка живёт не в
    //  миллисекундах, а в событиях, и одно и то же время означает разное на
    //  разных частотах: атака 5 мс на басу 50 Гц — это ЧЕТВЕРТЬ периода волны,
    //  то есть гейн успевает дёрнуться внутри одного колебания. Это уже не
    //  динамика, а искажение. На хэте те же 5 мс — целая вечность.
    //
    //  В FUTURE у каждого тона известна ЧАСТОТА, поэтому время можно задавать в
    //  ПЕРИОДАХ ЕГО СОБСТВЕННОЙ ВОЛНЫ. Одна ручка — и она сама ведёт себя
    //  правильно на всём спектре: бас физически невозможно промодулировать,
    //  а верх по-прежнему хватается мгновенно.
    //--------------------------------------------------------------------------

    // Сколько ПЕРИОДОВ волны тона занимает атака при ручке ATTACK в минимуме.
    // 1.0 = гейн не может измениться быстрее, чем за одно колебание.
    constexpr float futureAtkCyclesMax = 4.0f;   // ручка влево (мягко)
    constexpr float futureAtkCyclesMin = 0.5f;   // ручка вправо (резко)

    // Границы, за которые пересчёт в периоды не выпускает (мс). Нижняя не даёт
    // верхним тонам дёргаться быстрее кадра, верхняя — низу застревать навсегда.
    constexpr float futureAtkFloorMs = 1.0f;
    constexpr float futureAtkCeilMs  = 120.0f;

    //  РЕЛИЗ ОТ ТЕМПА ПРОЕКТА (только в FUTURE)
    //
    //  Обычный релиз задан в миллисекундах, поэтому настроенный под 128 BPM он уже
    //  не туда на 124. В танцевальной музыке релиз должен попадать МЕЖДУ долями, а
    //  доля — это темп, а не время.
    //  Поэтому ручка RELEASE в FUTURE задаёт ДОЛЮ ТАКТА, а темп берётся из
    //  НАСТРОЕК ПРОЕКТА (хост отдаёт выставленное число — он его не «угадывает»,
    //  ошибиться там нечему). Меняешь темп — релиз едет за ним сам.
    //
    //  Ручка ЩЁЛКАЕТ по нотам — промежуточных значений нет, в сетку попадаешь
    //  гарантированно, а не подбором. Список задан в kRelNotes (PluginProcessor.cpp):
    //  целая, половина, четверть, восьмая, шестнадцатая, плюс ТРИОЛИ (T) и
    //  ПУНКТИР (.) — свинг и полутона.
    //  Эти две границы остались для страховки, если нотный список вдруг пуст.
    constexpr float futureRelBeatsMax = 1.0f;    // целая доля
    constexpr float futureRelBeatsMin = 0.0625f; // 1/16 доли

    // Границы в мс — страховка на экстремальных темпах и когда хост темпа не даёт.
    constexpr float futureRelFloorMs = 20.0f;
    constexpr float futureRelCeilMs  = 1200.0f;

    //  ЗАМЕТКА НА БУДУЩЕЕ: релиз намеренно ОДИН на все тона (доля такта), хотя
    //  атака считается в периодах волны и потому у каждого тона своя. На бумаге
    //  это выглядит перекосом — на 8 кГц атака 1 мс, а релиз всё те же 234 мс.
    //  Пробовали укорачивать релиз на верхах: технически ровнее, но BEAT при этом
    //  превращается в SMART, и переключатель теряет смысл. Разница между ними —
    //  это ХАРАКТЕР, а не баг:
    //    BEAT  — весь спектр привязан к сетке, верх плотнее и ритмичнее.
    //    SMART — тон отпускается, когда реально стих; верх чище и свободнее.

    // Если хост не сообщает темп (standalone, некоторые оффлайн-рендеры) — берём это.
    constexpr double futureFallbackBpm = 128.0;

    // РЕЖИМ SMART (переключатель BEAT | SMART рядом с ручкой RELEASE):
    // доля такта становится МАКСИМУМОМ, но если тон стих раньше — отпускаем сразу,
    // не дожидаясь доли. Зачем: чистый темповый релиз держит паузу даже там, где
    // держать уже нечего (пропущенный кик, синкопа), и это как раз те места, где
    // слышно «что-то придавлено». Плюс темп ОДИН на трек, а тоны разные — хвост
    // ревера и хэт живут по-разному, и одна доля им обоим не подходит.
    //
    // Насколько тон должен упасть от своего пика, чтобы счесть его стихшим.
    // Меньше = отпускает раньше.
    constexpr float futureRelDropDb = 6.0f;

    // Во сколько раз быстрее отпускать стихший тон (относительно доли такта).
    constexpr float futureRelSmartScale = 0.25f;

    //--------------------------------------------------------------------------
    //  РЕЖИМ BOND — связывание тонов, которые ВСЕГДА звучат вместе
    //  (переключатель FREE | BOND под движком; FREE = как было)
    //
    //  Движок видит спектр как набор НЕЗАВИСИМЫХ тонов. Но в музыке они не
    //  независимы: кик и саб бьют вместе, это ОДИН источник. Сейчас они жмутся
    //  по-разному, и их баланс между собой едет от удара к удару — ухо слышит
    //  это как «низ гуляет».
    //
    //  BOND измеряет, насколько два тона синхронно ВСПЫХИВАЮТ. Если они десятки
    //  раз подряд начинались в одном кадре — это один источник, и им даётся общий
    //  гейн. Ключевое отличие от мультибэнда: связь берётся ИЗ МАТЕРИАЛА, а не
    //  задаётся полосами. Мультибэнд решает «что вместе» по частоте — грубо и
    //  всегда одинаково; здесь решает совместность во времени, то есть то, как
    //  музыка реально устроена.
    //--------------------------------------------------------------------------

    // Сколько ГЛАВНЫХ тонов вообще могут быть якорями связки. Матрица связей растёт
    // квадратом, поэтому берём только самые громкие. Больше = точнее, но дороже.
    constexpr int bondAnchors = 6;

    //--- ОГРАНИЧЕНИЯ (чтобы не связалось лишнее) -----------------------------
    // Связать лишнее — значит вернуть ровно тот пампинг, ради устранения которого
    // всё затевалось. Поэтому связь должна пройти ЧЕТЫРЕ проверки подряд:

    // 1. СОВПАДЕНИЕ. Насколько синхронно тона вспыхивают (0..1). Ниже — не связь,
    //    а случайность. 0.75 = совпали минимум в трёх случаях из четырёх.
    constexpr float bondMinAgreement = 0.75f;

    // 2. ВРЕМЯ. Сколько атак подряд должны совпасть, прежде чем поверим. Защита от
    //    случайного совпадения на одном ударе.
    constexpr int bondMinEvents = 8;

    // 3. РАССТОЯНИЕ. Дальше этого по частоте не связываем НИКОГДА (в октавах).
    //    Кик 50 Гц и хэт 8 кГц могут бить идеально синхронно всю дорогу — но это
    //    РАЗНЫЕ инструменты, и общий гейн им дал бы классическую накачку.
    constexpr float bondMaxOctaves = 3.5f;

    // 4. СИЛА. Насколько сильно подтягивать гейн к общему (0 = не связывать,
    //    1 = полностью общий гейн). Половина — намеренно: даже уверенная связь
    //    оставляет тонам часть собственной динамики.
    constexpr float bondStrength = 0.5f;

    // Как быстро забывается старая связь (доля за атаку). Меньше = держится дольше.
    constexpr float bondForget = 0.05f;
}
